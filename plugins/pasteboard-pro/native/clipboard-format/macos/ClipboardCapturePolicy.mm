#import "ClipboardCapturePolicy.h"
#import <UniformTypeIdentifiers/UniformTypeIdentifiers.h>

static NSString *const PBFConcealed = @"org.nspasteboard.ConcealedType";
static NSString *const PBFTransient = @"org.nspasteboard.TransientType";
static NSString *const PBFAutogenerated = @"org.nspasteboard.AutoGeneratedType";
static NSString *const PBFSourceMarker = @"org.nspasteboard.source";
static NSString *const PBFRemoteMarker = @"com.apple.is-remote-clipboard";

static NSSet<NSString *> *PBFLegacySensitiveTypes(void) {
    static NSSet<NSString *> *types;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        NSArray<NSString *> *tags = @[@"de.petermaurer.TransientPasteboardType",
                                      @"com.typeit4me.clipping",
                                      @"Pasteboard generator type",
                                      @"com.agilebits.onepassword"];
        NSMutableSet<NSString *> *names = [NSMutableSet setWithArray:tags];
        // AppKit translates historic non-UTI pasteboard tags into dynamic UTIs.
        // Match only aliases derived from these four known tags, never dyn.*.
        for (NSString *tag in tags) {
            UTType *withoutConformance = [UTType typeWithTag:tag
                tagClass:@"com.apple.nspboard-type" conformingToType:nil];
            UTType *dataConformance = [UTType typeWithTag:tag
                tagClass:@"com.apple.nspboard-type" conformingToType:UTTypeData];
            if (withoutConformance.identifier) [names addObject:withoutConformance.identifier];
            if (dataConformance.identifier) [names addObject:dataConformance.identifier];
        }
        types = [names copy];
    });
    return types;
}

static BOOL PBFIsBoundedBundleIdentifier(id value) {
    if (![value isKindOfClass:NSString.class] || [value length] == 0 || [value length] > 255) return NO;
    NSString *identifier = value;
    if ([identifier hasPrefix:@"."] || [identifier hasSuffix:@"."] ||
        [identifier containsString:@".."]) return NO;
    for (NSUInteger index = 0; index < identifier.length; index++) {
        unichar ch = [identifier characterAtIndex:index];
        if (!((ch >= 'A' && ch <= 'Z') || (ch >= 'a' && ch <= 'z') ||
              (ch >= '0' && ch <= '9') || ch == '-' || ch == '.')) return NO;
    }
    return YES;
}

NSDictionary<NSString *, id> *PBFDefaultCapturePolicy(void) {
    return @{@"paused" : @NO,
             @"allowUnknownSource" : @NO,
             @"allowLocalHistory" : @YES,
             @"excludedBundleIdentifiers" : @[]};
}

NSDictionary<NSString *, id> *_Nullable PBFNormalizeCapturePolicy(id policy) {
    if (![policy isKindOfClass:NSDictionary.class]) return nil;
    NSDictionary *input = policy;
    NSSet *keys = [NSSet setWithArray:PBFDefaultCapturePolicy().allKeys];
    if (![[NSSet setWithArray:input.allKeys] isEqual:keys]) return nil;
    NSMutableDictionary *normalized = [NSMutableDictionary dictionaryWithCapacity:keys.count];
    for (NSString *key in @[@"paused", @"allowUnknownSource", @"allowLocalHistory"]) {
        id flag = input[key];
        if (![flag isKindOfClass:NSNumber.class] ||
            CFGetTypeID((__bridge CFTypeRef)flag) != CFBooleanGetTypeID()) return nil;
        normalized[key] = @([flag boolValue]);
    }
    id rawRules = input[@"excludedBundleIdentifiers"];
    if (![rawRules isKindOfClass:NSArray.class] || [rawRules count] > 128) return nil;
    NSMutableArray<NSString *> *rules = [NSMutableArray arrayWithCapacity:[rawRules count]];
    NSMutableSet<NSString *> *seen = [NSMutableSet set];
    for (id value in rawRules) {
        if (!PBFIsBoundedBundleIdentifier(value) || [seen containsObject:value]) return nil;
        NSString *copied = [value copy];
        [rules addObject:copied];
        [seen addObject:copied];
    }
    normalized[@"excludedBundleIdentifiers"] = [rules copy];
    return [normalized copy];
}

BOOL PBFIsCapturePolicyMetadataType(NSString *name) {
    return [name isKindOfClass:NSString.class] &&
        ([name isEqual:PBFConcealed] || [name isEqual:PBFTransient] ||
         [name isEqual:PBFAutogenerated] || [name isEqual:PBFSourceMarker] ||
         [name isEqual:PBFRemoteMarker] || [PBFLegacySensitiveTypes() containsObject:name]);
}

NSDictionary<NSString *, id> *PBFEvaluateMacCapturePolicy(
    NSDictionary<NSString *, id> *normalizedPolicy,
    NSArray<NSArray<NSString *> *> *itemTypes,
    NSString *_Nullable frontmostBundleIdentifierHint) {
    BOOL concealed = NO, transient = NO, autogenerated = NO;
    BOOL sourceMarker = NO, remoteMarker = NO, legacySensitive = NO;
    BOOL complete = [itemTypes isKindOfClass:NSArray.class];
    NSSet *legacy = PBFLegacySensitiveTypes();
    for (id types in itemTypes) {
        if (![types isKindOfClass:NSArray.class]) { complete = NO; continue; }
        for (id name in types) {
            if (![name isKindOfClass:NSString.class]) { complete = NO; continue; }
            concealed |= [name isEqual:PBFConcealed];
            transient |= [name isEqual:PBFTransient];
            autogenerated |= [name isEqual:PBFAutogenerated];
            sourceMarker |= [name isEqual:PBFSourceMarker];
            remoteMarker |= [name isEqual:PBFRemoteMarker];
            legacySensitive |= [legacy containsObject:name];
        }
    }
    BOOL hintObserved = PBFIsBoundedBundleIdentifier(frontmostBundleIdentifierHint);
    NSArray<NSString *> *rules = normalizedPolicy[@"excludedBundleIdentifiers"];
    NSString *denial = @"none";
    if ([normalizedPolicy[@"paused"] boolValue]) denial = @"capture-paused";
    else if (![normalizedPolicy[@"allowLocalHistory"] boolValue]) denial = @"local-history-disabled-by-user";
    else if (!complete) denial = @"format-enumeration-incomplete";
    else if (hintObserved && [rules containsObject:frontmostBundleIdentifierHint]) denial = @"source-excluded";
    // A nonmatching foreground app does not prove the clipboard producer is
    // outside the exclusion list. Unknown producer identities fail closed.
    else if (rules.count > 0 || ![normalizedPolicy[@"allowUnknownSource"] boolValue]) denial = @"source-unknown";
    else if (concealed) denial = @"concealed-content";
    else if (transient) denial = @"transient-content";
    else if (autogenerated) denial = @"autogenerated-content";
    else if (legacySensitive) denial = @"legacy-sensitive-content";

    // Only fixed codes and booleans escape; hint/rule identifiers and marker
    // payloads never become receipt fields. Marker semantics are conventions.
    return @{@"captureAllowed" : @([denial isEqual:@"none"]),
             @"denialCode" : denial,
             @"sourceKind" : @"unknown",
             @"sourceAttribution" : @"unknown",
             @"producerIdentityVerified" : @NO,
             @"frontmostHintObserved" : @(hintObserved),
             @"frontmostHintAttribution" : hintObserved ? @"heuristic" : @"unknown",
             @"sourceMarkerPresent" : @(sourceMarker),
             @"remoteClipboardMarkerPresent" : @(remoteMarker),
             @"concealedMarkerPresent" : @(concealed),
             @"transientMarkerPresent" : @(transient),
             @"autogeneratedMarkerPresent" : @(autogenerated),
             @"legacySensitiveMarkerPresent" : @(legacySensitive),
             @"contentScanStatus" : @"not-scanned"};
}
