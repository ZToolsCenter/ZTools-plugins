const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const adapt = require('../../build-config/ztools/host-settings-loader.cjs')
const base = 'vendor/lx/src/renderer/views/setting/components/'
const transform = file => adapt.call({ resourcePath: base + file }, fs.readFileSync(base + file, 'utf8'))
test('approved host-owned controls disappear while every lyric setting remains', () => {
  const basic = transform('SettingBasic.vue')
  for (const id of ['setting_start_in_fullscreen', 'setting_to_tray', 'h3#basic_window_size', 'h3#basic_control_btn_position']) assert.ok(!basic.includes(id), id)
  assert.ok(basic.includes('h3#basic_font_size'))
  const play = transform('SettingPlay.vue')
  for (const id of ['setting_player_power_save_blocker', 'setting_player_showTaskProgess']) assert.ok(!play.includes(id), id)
  assert.ok(play.includes('setting_player_showStatusBarLyric'))
  assert.ok(play.includes('setting_player_lyric_transition'))
  const lyric = transform('SettingDesktopLyric.vue')
  assert.ok(lyric.includes('setting_desktop_lyric_fullscreen_hide'))
  assert.ok(lyric.includes('setting_desktop_lyric_pause_hide'))
  const other = transform('SettingOther.vue')
  for (const id of ['setting_transparent_window', 'h3#other_tray_theme', 'h3#other_resource_cache']) assert.ok(!other.includes(id), id)
  assert.ok(other.includes('h3#other_other_source'))
  assert.ok(other.includes('h3#other_lyric_edited'))
})
