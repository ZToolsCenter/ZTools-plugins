const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { createBridge } = require('../../src-ztools/preload/runtime/bridge.cjs')
const { initializeRuntime } = require('../../src-ztools/preload/runtime/index.cjs')
test('metadata and Explorer operate only on selected plugin files', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'lx-meta-host-'))
  const calls = [], bridge = createBridge()
  const runtime = initializeRuntime({ bridge, directory, ztools: { shellShowItemInFolder: file => calls.push(file) } })
  t.after(() => runtime.dispose())
  const fixture = path.resolve('tests/ztools/fixtures/download/tone.mp3')
  const file = path.join(directory, '中文.mp3')
  fs.copyFileSync(fixture, file)
  const metadata = await bridge.invoke('metadata:parseFile', [file])
  assert.ok(metadata.format.duration > 0.2)
  assert.ok(metadata.native)
  await bridge.invoke('host:openDirectory', file)
  assert.equal(calls[0], fs.realpathSync.native(file))
  await assert.rejects(bridge.invoke('metadata:parseFile', [fixture]), { code: 'PATH_NOT_GRANTED' })
  await assert.rejects(bridge.invoke('host:openDirectory', fixture), { code: 'PATH_NOT_GRANTED' })
})
