const { test } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, mkdirSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { createFileScope } = require('../../src-ztools/preload/runtime/files.cjs')

test('local file capabilities allow chosen paths and reject traversal outside roots', () => {
  const root = mkdtempSync(join(tmpdir(), 'lx-files-'))
  const inside = join(root, 'chosen'); mkdirSync(inside)
  const secret = join(root, 'other.txt'); writeFileSync(secret, 'outside')
  const scope = createFileScope([inside])
  assert.equal(scope.authorize(join(inside, 'new.txt')), join(inside, 'new.txt'))
  assert.throws(() => scope.authorize(join(inside, '..', 'other.txt')), { code: 'PATH_NOT_GRANTED' })
  scope.grant(secret, false)
  assert.equal(scope.authorize(secret), secret)
  assert.throws(() => scope.authorize(join(root, 'unselected.txt')), { code: 'PATH_NOT_GRANTED' })
})

test('a selected backup without an extension saves its LX filename without granting sibling access', async t => {
  const fs = require('node:fs')
  const { createDataService } = require('../../src-ztools/preload/runtime/data.cjs')
  const { createFileService } = require('../../src-ztools/preload/runtime/files.cjs')
  const root = mkdtempSync(join(tmpdir(), 'lx-backup-selected-root-'))
  const outside = mkdtempSync(join(tmpdir(), 'lx-backup-selected-file-'))
  const data = createDataService(root)
  t.after(() => data.close())
  const files = createFileService(data.getDatabase(), root)
  const selected = join(outside, '我的备份')
  files.scope.grant(selected, false)
  await files.call('saveLxConfigFile', [selected, { type: 'setting_v2', data: { 'player.volume': 0.4 } }])
  const document = JSON.parse(require('node:zlib').gunzipSync(fs.readFileSync(join(outside, '我的备份.lxmc'))))
  assert.equal(document.data['player.volume'], 0.4)
  assert.deepEqual(fs.readdirSync(outside), ['我的备份.lxmc'])
  assert.throws(() => files.scope.authorize(join(outside, '我的备份.lxmc')), { code: 'PATH_NOT_GRANTED' })
  await assert.rejects(files.call('saveStrToFile', [join(outside, 'another.txt'), 'no']), { code: 'PATH_NOT_GRANTED' })
})

test('backup extension derivation rejects a linked destination outside the selected directory', async t => {
  const fs = require('node:fs')
  const { createDataService } = require('../../src-ztools/preload/runtime/data.cjs')
  const { createFileService } = require('../../src-ztools/preload/runtime/files.cjs')
  const root = mkdtempSync(join(tmpdir(), 'lx-backup-link-root-'))
  const outside = mkdtempSync(join(tmpdir(), 'lx-backup-link-selection-'))
  const secret = mkdtempSync(join(tmpdir(), 'lx-backup-link-secret-'))
  fs.writeFileSync(join(secret, 'keep.txt'), 'original')
  const data = createDataService(root)
  t.after(() => data.close())
  const files = createFileService(data.getDatabase(), root)
  const selected = join(outside, 'backup')
  files.scope.grant(selected, false)
  fs.symlinkSync(secret, selected + '.lxmc', 'junction')
  await assert.rejects(files.call('saveLxConfigFile', [selected, { type: 'setting_v2', data: {} }]), { code: 'PATH_NOT_GRANTED' })
  assert.equal(fs.readFileSync(join(secret, 'keep.txt'), 'utf8'), 'original')
  assert.deepEqual(fs.readdirSync(secret), ['keep.txt'])
})
