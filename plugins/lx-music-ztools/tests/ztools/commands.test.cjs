const { test } = require('node:test')
const assert = require('node:assert/strict')
const { createBridge } = require('../../src-ztools/preload/runtime/bridge.cjs')
const { bindCommands } = require('../../src-ztools/preload/runtime/commands.cjs')
test('cold-start commands wait for original renderer readiness and dispatch once', async () => {
  const bridge = createBridge(), events = [], redirects = []
  const commands = bindCommands({ bridge, ztools: { redirectHotKeySetting: label => redirects.push(label) } })
  bridge.subscribe('commands:action', action => events.push(action))
  commands.enter({ code: 'next' }); commands.enter({ code: 'search', payload: 'lx 搜索 中文' })
  assert.equal(events.length, 0)
  const queued = await bridge.invoke('commands:ready')
  assert.deepEqual(queued.map(item => item.action.code), ['next', 'search'])
  assert.deepEqual(await bridge.invoke('commands:ready'), [])
  commands.enter({ code: 'play-pause' })
  assert.equal(events[0].action.code, 'play-pause')
  await bridge.invoke('host:hotkeySetting', 'LX 播放/暂停')
  assert.deepEqual(redirects, ['LX 播放/暂停'])
  await assert.rejects(bridge.invoke('host:hotkeySetting', 'other-plugin'))
  commands.dispose()
})
