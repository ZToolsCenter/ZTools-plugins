const { test } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const backend = require('../../src-ztools/preload/runtime/database.cjs')
const { createDataService } = require('../../src-ztools/preload/runtime/data.cjs')

test('original LX list methods preserve deduplication, move order and SQL rollback', () => {
  const dir = mkdtempSync(join(tmpdir(), 'lx-list-test-'))
  const data = createDataService(dir)
  const info = id => ({ id, name: id, source: null, sourceListId: null, locationUpdateTime: null })
  const music = (id, source) => ({ id, source, name: id, singer: 'test', interval: '00:01', meta: { musicId: 'same-platform-id', qualitys: [], _qualitys: {} } })
  const one = music('kw_1', 'kw'), two = music('tx_1', 'tx')
  data.call('list', 'createUserLists', [-1, [info('a'), info('b')]])
  data.call('list', 'musicsAdd', ['a', [one, two], 'bottom'])
  data.call('list', 'musicsAdd', ['a', [one], 'bottom'])
  assert.deepEqual(data.call('list', 'getListMusics', ['a']).map(x => x.id), ['kw_1', 'tx_1'])
  data.call('list', 'musicsMove', ['a', 'b', [one], 'top'])
  assert.deepEqual(data.call('list', 'getListMusics', ['a']).map(x => x.id), ['tx_1'])
  assert.deepEqual(data.call('list', 'getListMusics', ['b']).map(x => x.id), ['kw_1'])
  assert.throws(() => data.call('list', 'createUserLists', [-1, [info('c'), info('c')]]))
  assert.deepEqual(data.call('list', 'getAllUserList', []).map(x => x.id), ['a', 'b'])
  data.close()
  const reopened = createDataService(dir)
  assert.deepEqual(reopened.call('list', 'getListMusics', ['b']).map(x => x.id), ['kw_1'])
  reopened.close()
})
